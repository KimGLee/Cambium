    def rewrite_receipt_for_negative_test(self, receipt_id, mutate):
        for path in (self.root / ".cambium/receipts").rglob("*.jsonl"):
            records = [json.loads(line) for line in path.read_text(
                encoding="utf-8").splitlines() if line.strip()]
            matched = False
            for record in records:
                if record.get("receipt_id") == receipt_id:
                    mutate(record)
                    matched = True
            if matched:
                path.write_text("".join(json.dumps(record) + "\n"
                                        for record in records), encoding="utf-8")
                return
        self.fail("receipt %s was not found" % receipt_id)

    def remove_receipt_for_negative_test(self, receipt_id):
        """Temporarily remove one real receipt and return its exact bytes."""
        for path in (self.root / ".cambium/receipts").rglob("*.jsonl"):
            original = path.read_bytes()
            records = [json.loads(line) for line in original.decode(
                "utf-8").splitlines() if line.strip()]
            filtered = [record for record in records
                        if record.get("receipt_id") != receipt_id]
            if len(filtered) == len(records):
                continue
            path.write_text(
                "".join(json.dumps(record) + "\n" for record in filtered),
                encoding="utf-8")
            return path, original
        self.fail("receipt %s was not found" % receipt_id)

