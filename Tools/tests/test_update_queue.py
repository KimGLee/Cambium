    def restamp_close_bundle_version(self, close_gate_id, version):
        """Restamp one internally consistent current-shape producer bundle."""
        close_gate = self.close_bundle(close_gate_id)
        producer_evidence = dict(
            close_gate.get("closed_list_producer_evidence") or
            close_gate["closed_list_evidence"])
        bundle_ids = [
            close_gate_id,
            close_gate["global_review_receipt"],
            close_gate["reviewer_attestation_receipt"],
            *producer_evidence.values(),
        ]

        def restamp(record):
            record["tool_version"] = version
            if record.get("receipt_id") in (
                    close_gate_id, close_gate["global_review_receipt"]):
                # Historical producer eras predate full AuditReceipt wrappers:
                # their Closed List mapping names the original producer
                # evidence.  Reconstruct that actual era shape instead of
                # relabelling a current full AuditReceipt as legacy evidence.
                record["closed_list_evidence"] = dict(producer_evidence)
            if (record.get("check") == "batch_global_review_attestation" and
                    version not in
                    check_queue.COMPACT_CLOSE_EVIDENCE_VERSIONS):
                # A pre-compact era carried the full inline disposition
                # list; this fixture's bundle has zero candidates.
                record.setdefault("accepted_candidate_ids", [])

        for receipt_id in bundle_ids:
            self.rewrite_receipt_for_negative_test(receipt_id, restamp)

    def restamp_close_bundle_as_legacy_1_4(self, close_gate_id):
        """Reproduce the sealed seven-member check_batch_close 1.4 era."""
        close_gate = self.close_bundle(close_gate_id)
        producer_evidence = dict(
            close_gate.get("closed_list_producer_evidence") or
            close_gate["closed_list_evidence"])
        legacy_fields = (
            batch_close_contract.closed_list_evidence_fields_for_producer_version(
                "1.4.0")
        )
        omitted_fields = tuple(
            field
            for field in batch_close_contract.CLOSED_LIST_EVIDENCE_FIELDS
            if field not in legacy_fields
        )
        self.assertEqual(1, len(omitted_fields))
        legacy_evidence_ids = [
            receipt_id for field, receipt_id
            in producer_evidence.items()
            if field in legacy_fields
        ]
        legacy_evidence = {
            field: receipt_id
            for field, receipt_id in producer_evidence.items()
            if field in legacy_fields
        }
        bundle_ids = [
            close_gate_id,
            close_gate["global_review_receipt"],
            close_gate["reviewer_attestation_receipt"],
            *legacy_evidence_ids,
        ]

        def restamp(record):
            record["tool_version"] = "1.4.0"
            if record.get("receipt_id") in (
                    close_gate_id, close_gate["global_review_receipt"]):
                record["closed_list_evidence"] = dict(legacy_evidence)
            if record.get("check") == "batch_global_review_attestation":
                record.setdefault("accepted_candidate_ids", [])

        for receipt_id in bundle_ids:
            self.rewrite_receipt_for_negative_test(receipt_id, restamp)

    def detach_current_page_review_from_historical_bundle(self, close_gate_id):
        """Give live owner evidence a current attestation of its own.

        The historical-close tests deliberately restamp the frozen close
        bundle to an older producer era.  Current Coverage review ownership is
        not historical replay: it still requires a 1.11 page child and
        attestation.  Split that live edge before restamping so the fixture
        models the real case in which current owner evidence and an older
        closed bundle coexist without reinterpreting either era.
        """
        close_gate = self.close_bundle(close_gate_id)
        original_id = close_gate["reviewer_attestation_receipt"]
        catalog = check_queue.current_receipt_catalog(
            check_queue.validate_runtime(self.root))
        original = copy.deepcopy(catalog[original_id][1])
        current_id = original_id + "-current-owner"
        original["receipt_id"] = current_id
        kblib.write_receipts(
            self.root / ".cambium/receipts/fixture.jsonl", [original])
        for page_review_id in close_gate.get("page_review_receipts") or []:
            self.rewrite_receipt_for_negative_test(
                page_review_id,
                lambda record, value=current_id: record.__setitem__(
                    "reviewer_attestation_receipt", value))

